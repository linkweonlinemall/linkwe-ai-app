const assert=require('node:assert/strict'), fs=require('node:fs'), Module=require('node:module'), ts=require('typescript');
const filename=require('node:path').resolve('lib/vendor/order-workspace.ts');
const compiled=ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const mod=new Module(filename);mod._compile(compiled,filename);
const {orderBucket,orderNextStep,filterOrders,ordersCSV,productOrderRow,orderProgress,effectiveOrderStatus,safeOrderLink}=mod.exports;
const {SplitOrderStatus}=require('@prisma/client');
const now=Date.parse('2026-09-25T15:00:00Z');
const base={id:'order-1',kind:'product',reference:'LW-A123',secondaryReference:'SP-B456',title:'Cocoa gift set',customer:'Preview Customer',status:'AWAITING_VENDOR_ACTION',amountMinor:14500,currency:'TTD',createdAt:'2026-09-24T15:00:00Z',detail:'LinkWe delivery',href:'/order-1'};
const filters={search:'',bucket:'all',kind:'all',days:0,sort:'attention'};
const rows=Object.values(SplitOrderStatus).map((status,i)=>({...base,id:'order-'+i,status}));
assert.equal(filterOrders(rows,filters,now).length,Object.values(SplitOrderStatus).length);
assert.equal(['action','progress','completed','cancelled'].flatMap(bucket=>filterOrders(rows,{...filters,bucket},now)).length,rows.length);
assert.equal(orderBucket({...base,status:'READY_FOR_CUSTOMER_PICKUP'}),'progress');
assert.match(orderNextStep({...base,status:'READY_FOR_CUSTOMER_PICKUP'}),/customer collection/);
assert.equal(orderBucket({...base,inboundMethod:'VENDOR_DROPOFF'}),'progress');
assert.equal(orderProgress('READY_FOR_LINKWE',false,false).current,1,'not yet received by warehouse');
assert.equal(orderProgress('AT_WAREHOUSE',false,false).current,2);
assert.equal(orderProgress('CANCELLED',false,false),null);
assert.equal(orderProgress('DELIVERED',true,false).current,1);
assert.equal(effectiveOrderStatus('AWAITING_VENDOR_ACTION','PENDING_PAYMENT'),'PENDING_PAYMENT');
assert.equal(effectiveOrderStatus('PREPARING','REFUNDED'),'REFUNDED');
assert.equal(orderBucket({...base,status:effectiveOrderStatus('AWAITING_VENDOR_ACTION','CANCELLED')}),'cancelled');
assert.equal(filterOrders([base],{...filters,search:'b456 cocoa'},now).length,1);
assert.equal(filterOrders([base],{...filters,search:'different'},now).length,0);
assert.equal(filterOrders([base,{...base,id:'old',createdAt:'2026-08-01T15:00:00Z'}],{...filters,days:7},now).length,1);
const service={...base,kind:'quote',status:'PENDING',amountMinor:null};
assert.deepEqual(filterOrders([base,service],{...filters,kind:'quote'},now),[service]);
assert.equal(filterOrders([service,base],{...filters,sort:'value'},now)[0].amountMinor,14500);
const csv=ordersCSV([{...service,customer:'=HYPERLINK("https://example.com")',title:'Care, "cocoa"\nset'}]);
assert.ok(csv.startsWith('\uFEFF'));
assert.ok(csv.includes('"\'=HYPERLINK(""https://example.com"")"'));
assert.ok(csv.includes('"Care, ""cocoa""\nset"'));
assert.ok(csv.includes('"TTD","",'),'unquoted service has no invented zero price');
const split={id:'split',mainOrderId:'main',storeId:'store',referenceNumber:'REAL-SPLIT',status:'AWAITING_VENDOR_ACTION',subtotalMinor:14500,shippingMinor:0,currency:'TTD',createdAt:new Date(now),pickupRegion:null,vendorInboundMethod:null,items:[],mainOrder:{region:'San Fernando',referenceNumber:'REAL-MAIN',shippingAddressId:null,buyer:{fullName:'Preview'},items:[]}};
assert.equal(productOrderRow(split).reference,'REAL-MAIN');
assert.equal(productOrderRow(split).secondaryReference,'REAL-SPLIT');
assert.equal(productOrderRow(split).detail,'Warehouse pickup','empty items are not digital');
split.mainOrder.items=[{storeId:'store',product:{isDigital:true}}];
assert.equal(productOrderRow(split).detail,'Digital delivery');
assert.equal(safeOrderLink('javascript:alert(1)'),null);assert.equal(safeOrderLink('//example.com'),null);assert.equal(safeOrderLink('/\\example.com'),null);
assert.equal(safeOrderLink('https://example.com/photo.jpg'),'https://example.com/photo.jpg');
console.log('PASS: all order statuses remain visible; truthful progress; payment/closed-state overrides; reference search, dates, sorting, service filters; CSV escaping/formula protection; safe links and digital classification.');
